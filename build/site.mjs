#!/usr/bin/env node
// Builds the docs site (design.uniformrealestate.com) into _site/: site/index.html with token
// tables generated from tokens/tokens.json, plus the gallery and dist/. Run after `npm run build`.
import { readFileSync, writeFileSync, mkdirSync, rmSync, cpSync, readdirSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "_site");
const { version } = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
const tokens = JSON.parse(readFileSync(join(ROOT, "tokens/tokens.json"), "utf8"));
const esc = (s) =>
  String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
const entries = (group) => Object.entries(tokens[group]).filter(([k]) => !k.startsWith("$"));
const row = (cells) => `<tr>${cells.map((c) => `<td>${c}</td>`).join("")}</tr>`;
const code = (s) => `<code class="u-code">${esc(s)}</code>`;

const colors = entries("color").map(([k, v]) =>
  row([`<span class="s-swatch s-swatch--${k}"></span>`, code(`--u-${k}`), code(v.value), esc(v.note ?? "")]),
);
// Swatches are classes, not inline styles, so the page stays CSP-clean like every consumer.
const swatches = entries("color")
  .map(([k]) => `.s-swatch--${k} {\n  background: var(--u-${k});\n}\n`)
  .join("");
const simple = (group, prefix) =>
  entries(group).map(([k, v]) => row([code(`--u-${prefix}-${k}`), code(v.value)]));

const svgs = readdirSync(join(ROOT, "dist/svg"));
const marks = ["wordmark", "real-estate", "transaction"]
  .flatMap((m) => [
    [`uniform-${m}-color.svg`, "light", "on light"],
    [`uniform-${m}-on-dark.svg`, "dark", "on dark"],
  ])
  .concat([["uniform-icon.svg", "dark", "icon"]])
  .filter(([f]) => svgs.includes(f))
  .map(
    ([f, theme, label]) =>
      `<li data-theme="${theme}"><img src="dist/svg/${f}" alt="" width="200" height="56" /><a href="dist/svg/${f}">${esc(f)}</a><span class="u-meta">${label}</span></li>`,
  );

let html = readFileSync(join(ROOT, "site/index.html"), "utf8")
  .replaceAll("{{version}}", esc(version))
  .replace("<!--colors-->", colors.join("\n"))
  .replace("<!--space-->", simple("space", "space").join("\n"))
  .replace("<!--radius-->", simple("radius", "radius").join("\n"))
  .replace("<!--font-->", simple("font", "font").join("\n"))
  .replace("<!--marks-->", marks.join("\n"));
const left = html.match(/\{\{\w+\}\}|<!--\w+-->/);
if (left) throw new Error(`site/index.html: unfilled placeholder ${left[0]}`);

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT);
writeFileSync(join(OUT, "index.html"), html);
writeFileSync(join(OUT, "site.css"), readFileSync(join(ROOT, "site/site.css")));
writeFileSync(join(OUT, "swatches.css"), `/* Generated by build/site.mjs. */\n${swatches}`);
cpSync(join(ROOT, "dist"), join(OUT, "dist"), { recursive: true });
cpSync(join(ROOT, "gallery"), join(OUT, "gallery"), { recursive: true });
console.log(`_site/ built for v${version}`);
